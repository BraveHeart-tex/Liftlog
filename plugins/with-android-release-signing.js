const { copyFile, mkdir } = require('node:fs/promises');
const { join } = require('node:path');
const {
  createRunOncePlugin,
  withAppBuildGradle,
  withDangerousMod
} = require('expo/config-plugins');

const GENERATED_GRADLE_FILENAME = 'liftlog-release-signing.gradle';
const GRADLE_HOOK = `// @generated by with-android-release-signing
apply from: file("${GENERATED_GRADLE_FILENAME}")`;
const SOURCE_GRADLE_PATH = require.resolve(
  `./android/${GENERATED_GRADLE_FILENAME}`
);

function withAndroidReleaseSigning(config) {
  config = withAppBuildGradle(config, configMod => {
    if (configMod.modResults.language !== 'groovy') {
      throw new Error(
        'with-android-release-signing requires a Groovy app build.gradle'
      );
    }

    if (!configMod.modResults.contents.includes(GRADLE_HOOK)) {
      configMod.modResults.contents = `${configMod.modResults.contents.trimEnd()}\n\n${GRADLE_HOOK}\n`;
    }

    return configMod;
  });

  return withDangerousMod(config, [
    'android',
    async configMod => {
      const appDirectory = join(
        configMod.modRequest.platformProjectRoot,
        'app'
      );

      await mkdir(appDirectory, { recursive: true });
      await copyFile(
        SOURCE_GRADLE_PATH,
        join(appDirectory, GENERATED_GRADLE_FILENAME)
      );

      return configMod;
    }
  ]);
}

module.exports = createRunOncePlugin(
  withAndroidReleaseSigning,
  'with-android-release-signing',
  '1.0.0'
);
